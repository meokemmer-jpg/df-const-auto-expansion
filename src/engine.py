# ============================================================
# Konst-Detector
# ============================================================

class KonstDetector:
    """Detektiert Konst-IDs in klassen_variant_tables.py."""

    KONST_PATTERN = re.compile(r"['\"]([Kk]\d+|KONST_\d+)['\"]")

    @staticmethod
    def detect(python_path: Path) -> list[str]:
        """Returns sorted unique Liste aller Konst-IDs in der Datei."""
        if not python_path.exists():
            return []
        try:
            text = python_path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            return []
        matches = KonstDetector.KONST_PATTERN.findall(text)
        # Normalize: K01 == K1
        normed = set()
        for m in matches:
            if m.upper().startswith("K") and not m.startswith("KONST_"):
                # K01, K1 -> uniformize: K01 (zero-padded)
                num_part = m[1:]
                if num_part.isdigit():
                    normed.add(f"K{int(num_part):02d}")
                else:
                    normed.add(m.upper())
            else:
                normed.add(m.upper())
        return sorted(normed)


# ============================================================
# Existing-Scanner
# ============================================================

class ExistingScanner:
    """Findet welche Konsts schon 5-Tier + 50-Klausel-Skelett haben."""

    def __init__(self, vertrags_root: Path, klauseln_root: Path,
                 tiers_per_konst: int = 5, klauseln_per_konst: int = 50):
        self.vertrags_root = vertrags_root
        self.klauseln_root = klauseln_root
        self.tiers_per_konst = tiers_per_konst
        self.klauseln_per_konst = klauseln_per_konst

    def is_complete(self, konst_id: str) -> dict[str, Any]:
        """Returns {complete: bool, tiers_found: int, klauseln_found: int}."""
        tiers_dir = self.vertrags_root / konst_id
        klauseln_dir = self.klauseln_root / konst_id
        tiers_count = 0
        klauseln_count = 0
        if tiers_dir.exists():
            tiers_count = len([f for f in tiers_dir.glob("tier-*.yaml") if f.is_file()])
        if klauseln_dir.exists():
            klauseln_count = len([f for f in klauseln_dir.glob("klausel-*.md") if f.is_file()])
        complete = (tiers_count >= self.tiers_per_konst
                    and klauseln_count >= self.klauseln_per_konst)
        return {
            "konst_id": konst_id,
            "complete": complete,
            "tiers_found": tiers_count,
            "klauseln_found": klauseln_count,
        }


# ============================================================
# TierTemplateEngine
# ============================================================

class TierTemplateEngine:
    """Generiert 5-Tier-YAML-Skelette pro Konst."""

    @staticmethod
    def render(konst_id: str, tier: int) -> str:
        """Skelett-YAML fuer eine Konst-Tier-Kombination."""
        return (
            f"# Auto-generated by DF-CONST-AUTO-EXPANSION [CRUX-MK]\n"
            f"konst_id: {konst_id}\n"
            f"tier: Tier-{tier}\n"
            f"status: SKELETON\n"
            f"version: 0.1.0\n"
            f"created_iso: {datetime.now(tz=timezone.utc).isoformat()}\n"
            f"name: '{konst_id} Tier-{tier} (skeleton)'\n"
            f"variant_summary: |\n"
            f"  TODO: Inhalt fuer {konst_id} Tier-{tier} ergaenzen.\n"
            f"klauseln:\n"
            f"  - klausel_id: TODO\n"
            f"    text: TODO\n"
            f"acceptance_criteria:\n"
            f"  K11_cascade_isolation: TBD\n"
            f"  K12_provenance: auto-generated\n"
            f"  K13_external_anchor: github_filesystem\n"
            f"  K14_override_complexity: single_command\n"
            f"  K15_entropy_added_loc_estimate: 0\n"
            f"  K16_concurrent_spawn_protection: both\n"
        )

    def generate_for_konst(self, konst_id: str, tiers_dir: Path,
                          tiers_count: int = 5,
                          overwrite: bool = False) -> list[Path]:
        """Erstellt tier-1.yaml ... tier-N.yaml."""
        tiers_dir.mkdir(parents=True, exist_ok=True)
        created: list[Path] = []
        for tier in range(1, tiers_count + 1):
            path = tiers_dir / f"tier-{tier}.yaml"
            if path.exists() and not overwrite:
                continue
            path.write_text(TierTemplateEngine.render(konst_id, tier), encoding="utf-8")
            created.append(path)
        return created


