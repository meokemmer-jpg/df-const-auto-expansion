# Logger + Mutex (Pattern-Reuse)
# ============================================================

class AuditLogger:
    def __init__(self, log_path: Path):
        self.log_path = log_path
        self.log_path.parent.mkdir(parents=True, exist_ok=True)

    def log(self, event: dict[str, Any]) -> None:
        event["ts"] = event.get("ts", datetime.now(tz=timezone.utc).isoformat())
        with self.log_path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(event, ensure_ascii=False) + "\n")


class K16Mutex:
    def __init__(self, lock_dir: Path, stale_age_h: int = 3):
        self.lock_dir = lock_dir
        self.stale_age_h = stale_age_h

    def acquire(self) -> bool:
        if self.lock_dir.exists():
            stat = self.lock_dir.stat()
            age_s = time.time() - stat.st_mtime
            if age_s > self.stale_age_h * 3600:
                try:
                    pid_file = self.lock_dir / "pid"
                    if pid_file.exists():
                        pid_file.unlink()
                    self.lock_dir.rmdir()
                except OSError:
                    pass
        try:
            self.lock_dir.mkdir(parents=False, exist_ok=False)
            (self.lock_dir / "pid").write_text(str(os.getpid()))
            return True
        except FileExistsError:
            return False

    def release(self) -> None:
        try:
            pid_file = self.lock_dir / "pid"
            if pid_file.exists():
                pid_file.unlink()
            if self.lock_dir.exists():
                self.lock_dir.rmdir()
        except OSError:
            pass


@dataclass
class PreActionCheck:
    env_tag: str
    mount_point: str
    backup_status: str
    blast_radius: str
    reversibility_class: str
    timestamp_iso: str

    def passes(self) -> bool:
        if self.env_tag not in ("dev", "staging", "prod"):
            return False
        if self.reversibility_class not in ("state_only", "side_effect"):
            return False
        return True


# ============================================================
# Main-Run
# ============================================================

@dataclass
class ExpansionRunResult:
    run_id: str
    started_iso: str
    finished_iso: str
    konsts_detected: list[str]
    konsts_expanded: list[str]
    tier_files_created: int
    klausel_files_created: int
    skipped_due_to_stop_flag: bool

    def summary(self) -> dict[str, Any]:
        return {
            "run_id": self.run_id,
            "konsts_detected_count": len(self.konsts_detected),
            "konsts_expanded_count": len(self.konsts_expanded),
            "tier_files_created": self.tier_files_created,
            "klausel_files_created": self.klausel_files_created,
            "skipped": self.skipped_due_to_stop_flag,
        }


def run_expansion(
    base_dir: Path,
    config: dict,
    stop_flag: Path | None = None,
) -> ExpansionRunResult:
    """Hauptlauf."""
    run_id = f"expand-{datetime.now(tz=timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    started = datetime.now(tz=timezone.utc).isoformat()

    mutex = K16Mutex(Path(config["k16_concurrent_spawn_mutex"]["lock_dir"]))
    if not mutex.acquire():
        raise RuntimeError("K16-VETO: Lock held")

    try:
        if stop_flag and stop_flag.exists():
            return ExpansionRunResult(
                run_id=run_id,
                started_iso=started,
                finished_iso=datetime.now(tz=timezone.utc).isoformat(),
                konsts_detected=[],
                konsts_expanded=[],
                tier_files_created=0,
                klausel_files_created=0,
                skipped_due_to_stop_flag=True,
            )

        # K13-PAV
        pac = PreActionCheck(
            env_tag=os.environ.get("DF_ENV_TAG", "prod"),
            mount_point=str(base_dir),
            backup_status="git_mirror_ok" if base_dir.exists() else "missing",
            blast_radius="write_skeleton_yamls_plus_audit_log",
            reversibility_class="side_effect",
            timestamp_iso=datetime.now(tz=timezone.utc).isoformat(),
        )
        if not pac.passes():
            raise RuntimeError(f"K13-PAV-FAIL: {pac}")

        # Konst-Detection
        python_path = base_dir / config["paths"]["python_table_path"]
        konsts = KonstDetector.detect(python_path)

        # Existing-Scan + Expand
        scanner = ExistingScanner(
            base_dir / config["paths"]["vertrags_root"],
            base_dir / config["paths"]["klauseln_root"],
            tiers_per_konst=config["generation"]["tiers_per_konst"],
            klauseln_per_konst=config["generation"]["klauseln_per_konst"],
        )
        tier_engine = TierTemplateEngine()
        klausel_engine = KlauselTemplateEngine()
        expanded: list[str] = []
        tier_total = 0
        klausel_total = 0
        for konst in konsts:
            status = scanner.is_complete(konst)
            if status["complete"]:
                continue
            tiers_dir = base_dir / config["paths"]["vertrags_root"] / konst
            klauseln_dir = base_dir / config["paths"]["klauseln_root"] / konst
            new_tiers = tier_engine.generate_for_konst(
                konst, tiers_dir,
                tiers_count=config["generation"]["tiers_per_konst"],
                overwrite=config["generation"]["overwrite_existing"],
            )
            new_klauseln = klausel_engine.generate_for_konst(
                konst, klauseln_dir,
                klauseln_count=config["generation"]["klauseln_per_konst"],
                overwrite=config["generation"]["overwrite_existing"],
            )
            tier_total += len(new_tiers)
            klausel_total += len(new_klauseln)
            if new_tiers or new_klauseln:
                expanded.append(konst)

        # Audit-Log
        logger = AuditLogger(base_dir / config["paths"]["audit_log"])
        logger.log({
            "run_id": run_id,
            "konsts_detected": len(konsts),
            "konsts_expanded": len(expanded),
            "tier_files": tier_total,
            "klausel_files": klausel_total,
        })

        return ExpansionRunResult(
            run_id=run_id,
            started_iso=started,
            finished_iso=datetime.now(tz=timezone.utc).isoformat(),
            konsts_detected=konsts,
            konsts_expanded=expanded,
            tier_files_created=tier_total,
            klausel_files_created=klausel_total,
            skipped_due_to_stop_flag=False,
        )
    finally:
        mutex.release()


