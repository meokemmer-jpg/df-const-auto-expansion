class KlauselTemplateEngine:
    """Generiert 50-Klausel-MD-Skelette pro Konst."""

    @staticmethod
    def render(konst_id: str, klausel_num: int) -> str:
        kid = f"{konst_id}-K{klausel_num:03d}"
        return (
            f"# Klausel-Begruendung {kid} [CRUX-MK]\n\n"
            f"**Auto-generated by DF-CONST-AUTO-EXPANSION**\n"
            f"**Status:** SKELETON\n"
            f"**Created:** {datetime.now(tz=timezone.utc).isoformat()}\n\n"
            f"## Klausel-Text\n\n"
            f"TODO: Klausel-Text fuer {kid}.\n\n"
            f"## Begruendung\n\n"
            f"TODO: Rechtliche / wirtschaftliche / vertragliche Begruendung.\n\n"
            f"## Cross-Reference\n\n"
            f"- Konst: {konst_id}\n"
            f"- Klausel-Nummer: {klausel_num}\n\n"
            f"## CRUX-Bindung\n\n"
            f"- K_0 Schutz: TBD\n"
            f"- Q_0 Schutz: TBD\n"
            f"- W_0 Optimierung: TBD\n\n"
            f"[CRUX-MK]\n"
        )

    def generate_for_konst(self, konst_id: str, klauseln_dir: Path,
                           klauseln_count: int = 50,
                           overwrite: bool = False) -> list[Path]:
        klauseln_dir.mkdir(parents=True, exist_ok=True)
        created: list[Path] = []
        for n in range(1, klauseln_count + 1):
            path = klauseln_dir / f"klausel-{n:03d}.md"
            if path.exists() and not overwrite:
                continue
            path.write_text(KlauselTemplateEngine.render(konst_id, n), encoding="utf-8")
            created.append(path)
        return created


